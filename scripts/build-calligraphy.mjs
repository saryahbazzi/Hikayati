// Design-time tool: shapes "حكايتي" with Amiri (HarfBuzz), pairs every glyph with a hand-authored
// "pen path" and emits lib/calligraphy.ts. The pen paths become thick strokes in an SVG <mask>,
// which are drawn on over time to reveal the real calligraphic outline — a handwriting effect.
//
//   node scripts/build-calligraphy.mjs /path/to/Amiri-Regular.ttf [--debug out.svg]
import * as hb from "harfbuzzjs";
import fs from "node:fs";

const [, , fontPath, ...rest] = process.argv;
const debug = rest[0] === "--debug" ? rest[1] : null;
const data = fs.readFileSync(fontPath);
const face = new hb.Face(new hb.Blob(data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength)));
const font = new hb.Font(face);
const buf = new hb.Buffer();
buf.addText("حكايتي");
buf.guessSegmentProperties();
hb.shape(font, buf);
const infos = buf.getGlyphInfos();
const pos = buf.getGlyphPositions();
let pen = 0;
const shaped = infos.map((g, i) => {
  const r = { x: pen + pos[i].xOffset, y: pos[i].yOffset, d: font.glyphToPath(g.codepoint) };
  pen += pos[i].xAdvance;
  return r;
});

// Pen paths are authored directly in SVG units (see the --debug grid).
// pen.json is authored in debug-screenshot pixels (2000px-wide render): x = (px-79)*1.27, y = (py-788)*1.27.
const P = (s) => s.replace(/(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g, (_, x, y) => `${Math.round((x - 79) * 1.27)},${Math.round((y - 788) * 1.27)}`);

// Glyph order is visual (left → right): 0 ي  1 ت  2 ي  3 ا  4 ك  5 ح. Writing runs right → left (5 → 0).
// `s` = pen strokes, `c` = dots (grown as small circles), times in seconds from the start.
const PEN = JSON.parse(fs.readFileSync(new URL("./pen.json", import.meta.url), "utf8"));
const glyphs = shaped.map((g, i) => ({
  d: g.d,
  transform: `translate(${g.x} ${-g.y}) scale(1 -1)`,
  strokes: PEN[i].s.map((s) => ({ d: P(s.d), w: s.w, at: s.at, dur: s.dur })),
  dots: (PEN[i].c || []).map((c) => ({ cx: Math.round((c.x - 79) * 1.27), cy: Math.round((c.y - 788) * 1.27), r: c.r, at: c.at })),
}));
const out = `// GENERATED by scripts/build-calligraphy.mjs — do not edit by hand.
export const CALLIGRAPHY = ${JSON.stringify({ viewBox: "20 -790 2290 1360", glyphs }, null, 2)} as const;
`;
fs.writeFileSync(new URL("../lib/calligraphy.ts", import.meta.url), out);

if (debug) {
  let grid = '';
  for (let x = -100; x < 2500; x += 100) grid += `<line x1="${x}" y1="-1000" x2="${x}" y2="800" stroke="#ccc" stroke-width="2"/><text x="${x+4}" y="-960" font-size="34" fill="#888">${x}</text>`;
  for (let y = -1000; y < 800; y += 100) grid += `<line x1="-100" y1="${y}" x2="2439" y2="${y}" stroke="#ccc" stroke-width="2"/><text x="-96" y="${y-4}" font-size="34" fill="#888">${y}</text>`;
  const shapes = glyphs
    .map(
      (g, i) =>
        `<path transform="${g.transform}" d="${g.d}" fill="hsl(${i * 55} 35% 55%)" fill-opacity=".45"/>` +
        g.strokes.map((s) => `<path d="${s.d}" fill="none" stroke="hsl(${i * 55} 70% 30%)" stroke-opacity=".35" stroke-width="${s.w}" stroke-linecap="round" stroke-linejoin="round"/><path d="${s.d}" fill="none" stroke="red" stroke-width="5"/>`).join("") +
        g.dots.map((c) => `<circle cx="${c.cx}" cy="${c.cy}" r="${c.r}" fill="blue" fill-opacity=".25"/>`).join(""),
    )
    .join("");
  fs.writeFileSync(debug, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-100 -1000 2539 1800" width="2539"><rect x="-100" y="-1000" width="2539" height="1800" fill="#fff"/>${grid}${shapes}</svg>`);
}
