// Design-time tool: sets «حِكَايَتِي» in Amiri with HarfBuzz (full shaping, vowel marks included) and writes the
// outlines to lib/wordmark.ts as clean vector paths. The site renders that file; no font is needed at runtime.
//
//   node scripts/build-wordmark.mjs /path/to/Amiri-Regular.ttf
//
// REPLACEMENT SLOT: to use bespoke calligraphy, write lib/wordmark.ts in the same shape ({ viewBox, glyphs:[{ d, transform }] }).
import * as hb from "harfbuzzjs";
import opentype from "opentype.js";
import fs from "node:fs";

const [, , fontPath] = process.argv;
const data = fs.readFileSync(fontPath);
const ab = data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength);
const face = new hb.Face(new hb.Blob(ab));
const font = new hb.Font(face);
const ot = opentype.parse(ab);

const buf = new hb.Buffer();
buf.addText("حِكَايَتِي"); // ḥikāyatī — kasra, fatha, fatha, kasra
buf.guessSegmentProperties();
hb.shape(font, buf);
const infos = buf.getGlyphInfos(), pos = buf.getGlyphPositions();

let pen = 0, minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
const glyphs = infos.map((g, i) => {
  const x = pen + pos[i].xOffset, y = pos[i].yOffset;
  pen += pos[i].xAdvance;
  const bb = ot.glyphs.get(g.codepoint).getBoundingBox();
  // glyph space is y-up; the SVG flips it, so box → [x1, -y2, x2, -y1]
  minX = Math.min(minX, x + bb.x1); maxX = Math.max(maxX, x + bb.x2);
  minY = Math.min(minY, -(y + bb.y2)); maxY = Math.max(maxY, -(y + bb.y1));
  return { d: font.glyphToPath(g.codepoint), transform: `translate(${x} ${-y}) scale(1 -1)` };
});
const pad = 20;
const viewBox = [minX - pad, minY - pad, maxX - minX + pad * 2, maxY - minY + pad * 2].map(Math.round).join(" ");
fs.writeFileSync(new URL("../lib/wordmark.ts", import.meta.url),
  `// GENERATED by scripts/build-wordmark.mjs (Amiri, SIL OFL) — do not edit by hand.\nexport const WORDMARK = ${JSON.stringify({ viewBox, glyphs }, null, 2)} as const;\n`);
console.log("viewBox", viewBox, "glyphs", glyphs.length);
